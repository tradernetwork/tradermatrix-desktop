#!/usr/bin/env python3
"""Generates THIRD_PARTY_LICENSES.md: runtime (production) dependencies of the desktop app with versions and licenses.
Run from a checkout with node_modules installed and cargo available:  python3 scripts/gen_third_party.py > THIRD_PARTY_LICENSES.md
JS: `pnpm licenses list --prod --json` in apps/desktop. Rust: the NORMAL (non-dev, non-build) dependency closure of the
`tradermatrix-desktop` package for x86_64-unknown-linux-gnu from `cargo metadata`."""
import json, subprocess, sys, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def run(cmd, cwd):
    return subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, text=True).stdout

js = json.loads(run(["pnpm", "licenses", "list", "--prod", "--json"], os.path.join(root, "apps/desktop")))
js_rows = []
for lic, pkgs in js.items():
    for p in pkgs:
        for v in p.get("versions", [""]):
            js_rows.append((p["name"], v, lic, p.get("homepage") or ""))
js_rows.sort(key=lambda r: (r[0].lower(), r[1]))

tauri = os.path.join(root, "apps/desktop/src-tauri")
meta = json.loads(run(["cargo", "metadata", "--format-version", "1", "--filter-platform", "x86_64-unknown-linux-gnu"], tauri))
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
rootid = meta["resolve"]["root"]
seen, stack = set(), [rootid]
while stack:
    i = stack.pop()
    if i in seen:
        continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        if any(k["kind"] is None for k in d["dep_kinds"]):
            stack.append(d["pkg"])
rs_rows = sorted(
    {(pkgs[i]["name"], pkgs[i]["version"], pkgs[i].get("license") or "UNKNOWN", pkgs[i].get("repository") or "") for i in seen if i != rootid},
    key=lambda r: (r[0].lower(), r[1]),
)

def table(rows):
    out = ["| Package | Version | License | Source |", "|---|---|---|---|"]
    for n, v, l, h in rows:
        out.append(f"| {n} | {v} | {l} | {h} |")
    return "\n".join(out)

def tally(rows):
    t = {}
    for r in rows:
        t[r[2]] = t.get(r[2], 0) + 1
    return ", ".join(f"{k} ({v})" for k, v in sorted(t.items(), key=lambda kv: -kv[1]))

print("# Third-party licenses (runtime dependencies)\n")
print("Generated by `scripts/gen_third_party.py`. Production dependencies only; development tools are not shipped.\n")
print(f"## JavaScript (webview) : {len(js_rows)} packages\n\nLicense tally: {tally(js_rows)}\n")
print(table(js_rows))
print(f"\n## Rust (core, x86_64-unknown-linux-gnu) : {len(rs_rows)} crates\n\nLicense tally: {tally(rs_rows)}\n")
print(table(rs_rows))
print("\n## Bundled font files (not npm packages)\n\n| Font | License | Text |\n|---|---|---|\n| Inter (400, 500, 600, 700) | SIL OFL 1.1 | LICENSES/OFL-Inter.txt |\n| JetBrains Mono (400, 500, 700) | SIL OFL 1.1 | LICENSES/OFL-JetBrainsMono.txt |")
print("\nFull license texts: see each project's repository; Apache-2.0 text for KLineChart is in LICENSES/Apache-2.0.txt, font texts in LICENSES/OFL-*.txt.")
